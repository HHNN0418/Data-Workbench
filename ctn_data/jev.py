import json
import math
import socket

from .ai_providers import ProviderError, _TransportCancelled, _request_json, _text, _validate_key, _validate_url


API_BASE = 'https://api.typesafe.ai/v1'
MAX_STATE_BYTES = 80_000
RUBRIC_VERSION = 'ctn-account-evidence-v1'
DOCS_URL = 'https://docs.typesafe.ai/api'
JUDGMENT_CHOICES = {
    'evidence_sufficiency': ('insufficient', 'limited', 'adequate'),
    'automation_evidence': ('insufficient', 'weak', 'moderate', 'strong'),
    'coordinated_activity': ('insufficient', 'no_evidence', 'observed'),
}

