"""Native TypeSafe account-evidence review; it never reports an account.

Contract verified against https://docs.typesafe.ai/api and
https://docs.typesafe.ai/confidence on 2026-10-20. Model probabilities remain
unvalidated for CTN, whose NPC citizens also use AI systems.
"""
