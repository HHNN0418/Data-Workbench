import {StrictMode} from 'react';
import {createRoot} from 'react-dom/client';
import {BrowserRouter} from 'react-router-dom';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {ConfigProvider,App} from 'antd';
import zhCN from 'antd/locale/zh_CN';
import './ui/tokens.css';
import './style.css';
import {AuthGate} from './auth';
import AppShell from './nav/AppShell';
import AppRoutes from './routes';
import {antdTheme,applyCssVariables} from './ui/theme';
const client=new QueryClient({defaultOptions:{queries:{staleTime:15000,retry:1,refetchOnWindowFocus:false}}});
applyCssVariables();
createRoot(document.getElementById('root')!).render(<StrictMode><ConfigProvider locale={zhCN} theme={antdTheme}><App><QueryClientProvider client={client}><BrowserRouter><AuthGate><AppShell><AppRoutes/></AppShell></AuthGate></BrowserRouter></QueryClientProvider></App></ConfigProvider></StrictMode>);
